package instances

import (
	"context"

	"github.com/hostinger/api-cli/api"
	"github.com/hostinger/api-cli/output"
	"github.com/hostinger/api-cli/utils"
	"github.com/spf13/cobra"
)

var CredentialsCmd = &cobra.Command{
	Use:     "credentials <instance-id>",
	Short:   "Get instance credentials",
	Long:    "Retrieve SSH connection credentials (hostname, port, username and password) of a specified GPU instance.\n\nCredentials become available once the instance is provisioned; until then the endpoint responds with\n`409 Conflict`, so retry later.\n\nUse this endpoint to connect to a GPU instance over SSH.",
	Example: "  hostinger gpu instances credentials 6325",
	ValidArgsFunction: utils.CompleteArgs(
		&utils.ArgSource{
			Value: "id",
			Fetch: func(ctx context.Context, args []string) ([]byte, int, error) {
				r, err := api.CompletionRequest().GPUGetInstancesV1WithResponse(ctx)
				if err != nil {
					return nil, 0, err
				}
				return r.Body, r.StatusCode(), nil
			},
		},
	),
	RunE: func(cmd *cobra.Command, args []string) error {
		args = utils.PromptedArgs(cmd, args)
		call := func(ctx context.Context) ([]byte, int, error) {
			r, err := api.Request().GPUGetInstanceCredentialsV1WithResponse(ctx, utils.StringToInt(args[0]))
			if err != nil {
				return nil, 0, err
			}
			return r.Body, r.StatusCode(), nil
		}
		respBody, status, err := call(cmd.Context())
		if err != nil {
			return err
		}
		return output.Format(cmd, respBody, status)
	},
}

func init() {
	utils.RegisterArgs(CredentialsCmd, utils.IntArg("instance-id"))
}
