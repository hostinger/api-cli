package ssh_keys

import (
	"context"

	"github.com/hostinger/api-cli/api"
	"github.com/hostinger/api-cli/output"
	"github.com/hostinger/api-cli/utils"
	"github.com/spf13/cobra"
)

var ListVirtualMachineCmd = &cobra.Command{
	Use:     "list-virtual-machine <virtual-machine-id>",
	Short:   "List virtual machine SSH keys",
	Long:    "Retrieve SSH public keys currently configured on a specified virtual machine.\n\nOnly keys of the `root` user are listed.\n\nUse this endpoint to view SSH keys that can be used for authentication on VPS instances.",
	Example: "  hostinger vps ssh-keys list-virtual-machine 1268054",
	ValidArgsFunction: utils.CompleteArgs(
		&utils.ArgSource{
			Value: "id",
			Fetch: func(ctx context.Context, args []string) ([]byte, int, error) {
				r, err := api.CompletionRequest().VPSGetVirtualMachinesV1WithResponse(ctx)
				if err != nil {
					return nil, 0, err
				}
				return r.Body, r.StatusCode(), nil
			},
		},
	),
	RunE: func(cmd *cobra.Command, args []string) error {
		args = utils.PromptedArgs(cmd, args)
		call := func(ctx context.Context) ([]byte, int, error) {
			r, err := api.Request().VPSListVirtualMachineSSHKeysV1WithResponse(ctx, utils.StringToInt(args[0]))
			if err != nil {
				return nil, 0, err
			}
			return r.Body, r.StatusCode(), nil
		}
		respBody, status, err := call(cmd.Context())
		if err != nil {
			return err
		}
		return output.Format(cmd, respBody, status)
	},
}

func init() {
	utils.RegisterArgs(ListVirtualMachineCmd, utils.IntArg("virtual-machine-id"))
}
