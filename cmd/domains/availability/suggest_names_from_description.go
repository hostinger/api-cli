package availability

import (
	"bytes"
	"context"
	"encoding/json"

	"github.com/hostinger/api-cli/api"
	"github.com/hostinger/api-cli/output"
	"github.com/hostinger/api-cli/utils"
	"github.com/spf13/cobra"
)

var SuggestNamesFromDescriptionCmd = &cobra.Command{
	Use:               "suggest-names-from-description",
	Short:             "Suggest domain names from a description",
	Long:              "Suggest available domain names based on a free-text description of your project.\n\nSuggestions are generated by an AI model, so they differ between calls.\n\nEndpoint has rate limit of 90 requests per minute.\n\nUse this endpoint to find a domain name when you only know what the website is about.",
	Example:           "  hostinger domains availability suggest-names-from-description --description 'A bakery in Vilnius selling sourdough bread and pastries' --limit 10",
	ValidArgsFunction: cobra.NoFileCompletions,
	RunE: func(cmd *cobra.Command, args []string) error {
		args = utils.PromptedArgs(cmd, args)
		body, err := suggestNamesFromDescriptionBody(cmd)
		if err != nil {
			return err
		}
		payload, err := json.Marshal(body)
		if err != nil {
			return err
		}
		call := func(ctx context.Context) ([]byte, int, error) {
			r, err := api.Request().DomainsSuggestDomainNamesFromADescriptionV1WithBodyWithResponse(ctx, "application/json", bytes.NewReader(payload))
			if err != nil {
				return nil, 0, err
			}
			return r.Body, r.StatusCode(), nil
		}
		respBody, status, err := call(cmd.Context())
		if err != nil {
			return err
		}
		return output.Format(cmd, respBody, status)
	},
}

func init() {
	utils.RegisterArgs(SuggestNamesFromDescriptionCmd)
	SuggestNamesFromDescriptionCmd.Flags().StringP("description", "", "", "Free-text description of the project the domain is needed for")
	SuggestNamesFromDescriptionCmd.Flags().IntP("limit", "", 0, "Amount of domain names to suggest")
	SuggestNamesFromDescriptionCmd.MarkFlagRequired("description")
	SuggestNamesFromDescriptionCmd.MarkFlagRequired("limit")
	SuggestNamesFromDescriptionCmd.RegisterFlagCompletionFunc("description", cobra.NoFileCompletions)
	SuggestNamesFromDescriptionCmd.RegisterFlagCompletionFunc("limit", cobra.NoFileCompletions)
}

func suggestNamesFromDescriptionBody(cmd *cobra.Command) (map[string]any, error) {
	body := map[string]any{}
	descriptionVal, _ := cmd.Flags().GetString("description")
	body["description"] = descriptionVal
	limitVal, _ := cmd.Flags().GetInt("limit")
	body["limit"] = limitVal
	return body, nil
}
