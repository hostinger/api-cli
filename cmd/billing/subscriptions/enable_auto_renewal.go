package subscriptions

import (
	"context"

	"github.com/hostinger/api-cli/api"
	"github.com/hostinger/api-cli/output"
	"github.com/hostinger/api-cli/utils"
	"github.com/spf13/cobra"
)

var EnableAutoRenewalCmd = &cobra.Command{
	Use:     "enable-auto-renewal <subscription-id>",
	Short:   "Enable auto-renewal",
	Long:    "Enable auto-renewal for a subscription.\n\nUse this endpoint when enable auto-renewal for a subscription.",
	Example: "  hostinger billing subscriptions enable-auto-renewal Cxy353Uhl1xC54pG6",
	ValidArgsFunction: utils.CompleteArgs(
		&utils.ArgSource{
			Value: "id",
			Fetch: func(ctx context.Context, args []string) ([]byte, int, error) {
				r, err := api.CompletionRequest().BillingGetSubscriptionListV1WithResponse(ctx)
				if err != nil {
					return nil, 0, err
				}
				return r.Body, r.StatusCode(), nil
			},
		},
	),
	RunE: func(cmd *cobra.Command, args []string) error {
		args = utils.PromptedArgs(cmd, args)
		call := func(ctx context.Context) ([]byte, int, error) {
			r, err := api.Request().BillingEnableAutoRenewalV1WithResponse(ctx, args[0])
			if err != nil {
				return nil, 0, err
			}
			return r.Body, r.StatusCode(), nil
		}
		respBody, status, err := call(cmd.Context())
		if err != nil {
			return err
		}
		return output.Format(cmd, respBody, status)
	},
}

func init() {
	utils.RegisterArgs(EnableAutoRenewalCmd, utils.StringArg("subscription-id"))
}
